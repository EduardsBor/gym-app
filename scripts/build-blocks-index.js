'use strict';
// Build a small catalog index from data/blocks/*.json (no workout items).
// Run: node scripts/build-blocks-index.js
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'data', 'blocks');
const outJs = path.join(root, 'data', 'blocks-index.js');
const ID_RE = /^[a-z]+_[a-z]+_[0-9]+_(g|d|b_bar|b_nobar)(?:_pr_[a-z]+)?_b\d+$/;

function placeFromId(id) {
  const m = /_(g|d|b_bar|b_nobar)(?:_pr_[a-z]+)?_b\d+$/.exec(id);
  return m ? m[1] : null;
}

function build() {
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort();
  const items = [];
  for (const f of files) {
    const stem = f.slice(0, -5);
    if (!ID_RE.test(stem)) throw new Error('unrecognized block file name: ' + f);
    const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    const id = d.id || stem;
    if (id !== stem) throw new Error('id mismatch in ' + f + ': ' + id);
    items.push({
      id,
      key: d.key || null,
      goal: d.goal,
      level: d.level,
      days: d.days_per_week,
      place: placeFromId(stem),
      title: d.title || '',
      workouts: d.workouts_count || (Array.isArray(d.workouts) ? d.workouts.length : 0),
      weeks: d.weeks_at_plan_pace || 0,
      duration_label: d.duration_label || '60–70 мин',
      prio: /_pr_/.test(stem)
    });
  }
  const body = "'use strict';\n// Generated by scripts/build-blocks-index.js — do not edit by hand.\nvar BLOCK_INDEX=" + JSON.stringify(items) + ';\n';
  fs.writeFileSync(outJs, body);
  return items;
}

if (require.main === module) {
  const items = build();
  console.log('wrote', items.length, 'entries to data/blocks-index.js');
}

module.exports = { build, ID_RE, placeFromId };
