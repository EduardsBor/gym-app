'use strict';
/**
 * D-234: public privacy.html and terms.html generated from legal.js (RU/EN/LV, all three sections).
 * Static pages: no app scripts, no service worker, no sign-in gate. Run: node scripts/build-legal-pages.js
 * test/d234-legal-pages.test.js checks that the pages match legal.js.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');

function loadLegal() {
  const ctx = vm.createContext({ window: {} });
  vm.runInContext(fs.readFileSync(path.join(root, 'legal.js'), 'utf8') + '\n;this.__L = LEGAL;', ctx);
  return ctx.__L;
}
const LANGS = [['ru', 'Русский'], ['en', 'English'], ['lv', 'Latviešu']];
const OTHER = { privacy: ['terms.html', { ru: 'Условия использования', en: 'Terms of Use', lv: 'Lietošanas noteikumi' }], terms: ['privacy.html', { ru: 'Политика конфиденциальности', en: 'Privacy Policy', lv: 'Privātuma politika' }] };
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function page(L, key) {
  const t = L.en[key][0];
  const [otherHref, otherName] = OTHER[key];
  const nav = LANGS.map(([l, n]) => `<a href="#${l}">${n}</a>`).join(' · ');
  const secs = LANGS.map(([l]) => {
    const [title, note, html] = L[l][key];
    return `<section id="${l}" lang="${l}"><h1>${esc(title)}</h1>${note ? `<p class="note">${esc(note)}</p>` : ''}${html}
<p class="links"><a href="${otherHref}#${l}">${esc(otherName[l])}</a> · <a href="./">GymCaptain</a></p></section>`;
  }).join('\n<hr>\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>GymCaptain — ${esc(t)}</title><meta name="robots" content="index,follow">
<style>body{font:16px/1.55 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;margin:0 auto;padding:16px;color:#1b1d21;background:#fff}
h1{font-size:26px;margin:24px 0 8px}h3{margin:20px 0 6px}a{color:#2563eb}.top{position:sticky;top:0;background:#fff;padding:8px 0;border-bottom:1px solid #ddd}
.note{background:#fff7d6;border:1px solid #f0d36b;padding:8px 10px;border-radius:8px;font-size:14px}.links{margin-top:20px}hr{margin:32px 0;border:0;border-top:1px solid #ddd}
.card{background:none;padding:0}</style></head>
<body><!-- Generated by scripts/build-legal-pages.js from legal.js. Do not edit by hand. -->
<div class="top"><b>GymCaptain</b> · ${nav}</div>
${secs}
</body></html>
`;
}

function build() {
  const L = loadLegal();
  const out = {};
  for (const key of ['privacy', 'terms']) out[key + '.html'] = page(L, key);
  return out;
}
module.exports = { build };
if (require.main === module) {
  const out = build();
  for (const [f, html] of Object.entries(out)) fs.writeFileSync(path.join(root, f), html);
  console.log('written: ' + Object.keys(out).join(', '));
}
