function build() {
  const L = loadLegal();
  const out = {};
  for (const key of ['privacy', 'terms']) out[key + '.html'] = page(L, key);
  out['delete-account.html'] = deleteAccountPage();
  return out;
}

function writePages(dir, files) {
  fs.mkdirSync(dir, { recursive: true });
  for (const [f, html] of Object.entries(files)) fs.writeFileSync(path.join(dir, f), html);
}

function siteCopies(out) {
  return {
    'privacy.html': out['privacy.html'],
    'terms.html': out['terms.html'],
    'delete-account.html': out['delete-account.html']
  };
}

module.exports = { build, deleteAccountPage, writePages, siteCopies };
if (require.main === module) {
  const out = build();
  const args = process.argv.slice(2);
  const si = args.indexOf('--site');
  const siteDir = si >= 0 ? args[si + 1] : null;
  // App root: privacy + terms (D-234). delete-account.html is written too when
  // it matches the builder; do not change its committed bytes.
  for (const f of ['privacy.html', 'terms.html', 'delete-account.html']) {
    fs.writeFileSync(path.join(root, f), out[f]);
  }
  console.log('written: privacy.html, terms.html, delete-account.html');
  if (siteDir) {
    writePages(siteDir, siteCopies(out));
    console.log('site copies written: ' + siteDir);
  }
}
