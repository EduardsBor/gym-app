const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');

function loadLegal() {
  const ctx = vm.createContext({ window: {} });
  vm.runInContext(fs.readFileSync(path.join(root, 'legal.js'), 'utf8') + '\n;this.__L = LEGAL;', ctx);
  return ctx.__L;
}
