'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { build, ID_RE } = require('../scripts/build-blocks-index.js');

const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

function boot() {
  const store = new Map();
  const nodes = new Map();
  function el(id) {
    if (id && nodes.has(id)) return nodes.get(id);
    const node = {
      id: id || '', innerHTML: '', textContent: '', className: '', value: '', style: {}, dataset: {},
      classList: { toggle() {}, add() {}, remove() {}, contains() { return false; } },
      append() {}, addEventListener() {}, insertAdjacentHTML() {}, setAttribute() {}, getAttribute() { return null; },
      closest() { return null; }, querySelector() { return null; }, querySelectorAll() { return []; },
      onclick: null
    };
    if (id) nodes.set(id, node);
    return node;
  }
  const g = {
    console, setTimeout, clearTimeout, setInterval() { return 0; }, clearInterval() {},
    URL, Blob, navigator: { language: 'ru', languages: ['ru'] },
    localStorage: { getItem: k => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)), removeItem: k => store.delete(k) },
    location: { href: 'http://127.0.0.1/', origin: 'http://127.0.0.1', pathname: '/', search: '' },
    document: {
      documentElement: { lang: 'ru' }, title: '', body: { append() {}, style: {} },
      querySelector(sel) { const m = /^#([\w-]+)/.exec(sel || ''); return el(m ? m[1] : ''); },
      querySelectorAll() { return []; }, addEventListener() {}, createElement() { return el(); }
    }
  };
  g.window = g; g.globalThis = g; g.self = g;
  g.XMLHttpRequest = function () {
    this.status = 0; this.responseText = '';
    this.open = function (method, url) { this._url = url; };
    this.send = function () {
      const rel = String(this._url || '').replace(/^\.\//, '');
      const fp = path.join(root, rel);
      if (fs.existsSync(fp)) { this.status = 200; this.responseText = fs.readFileSync(fp, 'utf8'); }
      else { this.status = 404; this.responseText = ''; }
    };
  };
  const ctx = vm.createContext(g);
  const files = ['alt.js', 'i18n/dict.js', 'i18n/dict2.js', 'i18n/dict3.js', 'i18n/i18n.js', 'data/blocks-index.js', 'app.js', 'tech.js', 'lib.js', 'i18n/lib.en.js', 'i18n/lib.lv.js', 'i18n/tech.en.js', 'i18n/tech.lv.js', 'cards.js', 'warm.js', 'cd.js', 'place.js', 'prog.js', 'plan.js', 'blocks.js', 'legal.js', 'premium.js', 'features.js'];
  for (const f of files) vm.runInContext(read(f), ctx, { filename: f });
  return { run: code => vm.runInContext(code, ctx), app: () => vm.runInContext('app.innerHTML', ctx), ctx };
}

test('blocks-index is generated, complete, and matches data/blocks without embedding workouts', () => {
  const generated = build();
  const committed = read('data/blocks-index.js');
  const fresh = "'use strict';\n// Generated by scripts/build-blocks-index.js — do not edit by hand.\nvar BLOCK_INDEX=" + JSON.stringify(generated) + ';\n';
  assert.equal(committed, fresh);
  const files = fs.readdirSync(path.join(root, 'data/blocks')).filter(f => f.endsWith('.json')).sort();
  assert.equal(generated.length, files.length);
  assert.equal(generated.length, 244);
  const by = { g: 0, d: 0, b_bar: 0, b_nobar: 0 };
  for (const b of generated) {
    assert.ok(ID_RE.test(b.id), b.id);
    assert.ok(Object.prototype.hasOwnProperty.call(by, b.place), b.place);
    by[b.place]++;
    assert.equal(Object.prototype.hasOwnProperty.call(b, 'workouts_items') || Array.isArray(b.workouts_items), false);
    assert.equal('workouts' in b && Array.isArray(b.workouts), false);
    assert.ok(b.title && b.workouts >= 1 && b.weeks >= 1);
  }
  assert.deepEqual(by, { g: 64, d: 60, b_bar: 60, b_nobar: 60 });
  assert.equal(generated.filter(b => b.prio).length, 4);
  assert.equal(committed.includes('XMLHttpRequest'), false);
  const html = read('index.html');
  const sw = read('sw.js');
  assert.match(html, /src="data\/blocks-index\.js"/);
  assert.match(sw, /data\/blocks-index\.js/);
  assert.match(sw, /const C='moyzal-v135'/);
});

test('ready-program catalog keeps 13 curated cards, fills every chip combination, and does not generate in the list', () => {
  const { run, app } = boot();
  assert.equal(run('CATALOG.length'), 13);
  const n = run('catalogCards().length');
  assert.ok(n > 13);
  assert.equal(run('catalogCards().filter(c=>/^c\\d+$/.test(c.id)).length'), 13);
  assert.equal(run('CATALOG.some(c=>c.a.place==="d")'), false);
  assert.equal(run('catalogCards().some(c=>catalogCardPlace(c)==="d")'), false);
  assert.equal(run('catalogCards().some(c=>c.a.place==="b_bar")'), false);
  const chips = JSON.parse(run('JSON.stringify(catalogChipOptions())'));
  assert.deepEqual(chips.place, ['g', 'b']);
  assert.deepEqual(chips.days, [2, 3, 4, 5, 6]);
  const goals = [''].concat(chips.goal);
  const levels = [''].concat(chips.level);
  const days = [''].concat(chips.days);
  const places = [''].concat(chips.place);
  let min = Infinity, combos = 0, empty = [];
  const perChip = {};
  for (const goal of goals) for (const level of levels) for (const d of days) for (const place of places) {
    const F = {};
    if (goal) F.goal = goal;
    if (level) F.level = level;
    if (d) F.days = d;
    if (place) F.place = place;
    const count = run('filterCatalog(' + JSON.stringify(F) + ').length');
    combos++;
    if (count < min) min = count;
    if (count < 1) empty.push(F);
    const keys = Object.keys(F);
    if (keys.length === 1) perChip[keys[0] + '=' + F[keys[0]]] = count;
    if (keys.length === 0) perChip['all'] = count;
  }
  assert.deepEqual(empty, []);
  assert.ok(min >= 1, 'min combo count ' + min);
  assert.equal(combos, goals.length * levels.length * days.length * places.length);
  // stash for humans reading the test output
  console.log('per-chip (single filter)', perChip, 'min', min, 'combos', combos, 'total cards', n);
  run('S.goal=null;S.program=null;catF={};view="catalog";catalog()');
  const h = app();
  assert.match(h, /Найдено: /);
  assert.equal((h.match(/data-c="/g) || []).length, n);
  const src = read('app.js');
  const catFn = src.match(/function catalog\(\)\{[\s\S]*?\nfunction /)[0];
  assert.equal(/generate\(c\.a\)/.test(catFn), false);
  assert.equal(/XMLHttpRequest/.test(catFn), false);
  assert.match(src, /function filterCatalog\(/);
});

test('opening a ready-program card starts the same block as the questionnaire; history shape is unchanged', () => {
  const { run } = boot();
  const a = { goal: 'loss', level: 'mid', days: 3, place: 'g', sex: 'm', prio: [], lim: [], len: 70 };
  const want = run('blockIdForProfile(' + JSON.stringify(a) + ')');
  assert.equal(want, 'loss_mid_3_g_b36');
  const cardId = run('filterCatalog({goal:"loss",level:"mid",days:3,place:"g"}).find(c=>!(c.a.prio&&c.a.prio.length)).id');
  assert.ok(String(cardId).startsWith('blk-'));
  run('S.goal=null;S.program=null;S.workouts=[];S.block=null;preview(catalogFind(' + JSON.stringify(cardId) + '),"catalog")');
  const genId = run('PV.gen&&PV.gen.blockId');
  assert.equal(genId, want);
  run('this.confirm=()=>true;this.scrollTo=()=>{};this.toast=()=>{};');
  const before = run('JSON.stringify({workouts:S.workouts,program:S.program})');
  run('document.querySelector("#pstart")&&document.querySelector("#pstart").onclick&&document.querySelector("#pstart").onclick()');
  assert.equal(run('S.goal'), 'loss');
  assert.equal(run('S.days'), 3);
  assert.ok(run('S.program&&S.program.length>0'));
  assert.equal(run('S.block&&S.block.id'), want);
  assert.equal(run('JSON.stringify(S.workouts)'), '[]');
  // history array still starts empty; program is new on purpose
  assert.notEqual(run('JSON.stringify({workouts:S.workouts,program:S.program})'), before);
  // curated card with prio still exists and still uses generate(pr.a)
  assert.equal(run('CATALOG.some(c=>c.name==="Широкая спина"&&c.a.prio&&c.a.prio[0]==="Спина")'), true);
  const qId = run('blockIdForProfile({goal:"loss",level:"mid",days:3,place:"g",sex:"m",prio:[],lim:[]})');
  assert.equal(qId, want);
});
