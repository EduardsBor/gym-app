'use strict';
// D-274: gymcaptain-site legal page copies come from the same builder as gym-app
// (privacy/terms from legal.js; delete-account from the shared generator).
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const { build, siteCopies, writePages } = require('../scripts/build-legal-pages.js');

test('D-274: site legal copies match legal.js; delete-account matches the shared builder', () => {
  const out = build();
  const copies = siteCopies(out);
  assert.deepEqual(Object.keys(copies).sort(), ['delete-account.html', 'privacy.html', 'terms.html']);

  // Privacy and terms on the site are the same pages already kept in sync with legal.js (D-234).
  assert.equal(copies['privacy.html'], out['privacy.html']);
  assert.equal(copies['terms.html'], out['terms.html']);
  assert.equal(copies['privacy.html'], read('privacy.html'));
  assert.equal(copies['terms.html'], read('terms.html'));
  const legal = read('legal.js');
  assert.ok(legal.includes('Eduards Boroda (private individual, Latvia)'));
  assert.ok(copies['privacy.html'].includes('Eduards Boroda (private individual, Latvia)'));
  assert.ok(copies['privacy.html'].includes('Редакция от 21.11.2026'));
  assert.ok(copies['terms.html'].includes('Terms of Use'));
  assert.ok(copies['terms.html'].includes('Lietošanas noteikumi'));

  // Delete-account is generated by the same script (not edited by hand in the site repo).
  assert.equal(copies['delete-account.html'], out['delete-account.html']);
  assert.equal(copies['delete-account.html'], read('delete-account.html'));
  assert.match(copies['delete-account.html'], /Delete your GymCaptain account/);
  assert.match(copies['delete-account.html'], /Удаление аккаунта GymCaptain/);
  assert.match(copies['delete-account.html'], /GymCaptain konta dzēšana/);

  for (const [f, html] of Object.entries(copies)) {
    assert.doesNotMatch(html, /<script|serviceWorker|sw\.js|supabase-config|vendor\/supabase|#mzemail|#mzgate/i, f);
    for (const l of ['ru', 'en', 'lv']) assert.match(html, new RegExp(`<section id="${l}" lang="${l}">`), f);
  }
});

test('D-274: --site writes the three copies and does not alter app page bytes', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gc-site-legal-'));
  try {
    const before = {
      privacy: read('privacy.html'),
      terms: read('terms.html'),
      del: read('delete-account.html')
    };
    const r = spawnSync(process.execPath, [path.join(root, 'scripts/build-legal-pages.js'), '--site', dir], {
      cwd: root, encoding: 'utf8'
    });
    assert.equal(r.status, 0, r.stderr || r.stdout);
    for (const f of ['privacy.html', 'terms.html', 'delete-account.html']) {
      assert.equal(fs.readFileSync(path.join(dir, f), 'utf8'), read(f), f);
    }
    assert.equal(read('privacy.html'), before.privacy);
    assert.equal(read('terms.html'), before.terms);
    assert.equal(read('delete-account.html'), before.del);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
